# letter answers (a-e) → index 11-15 (⓪-⑨=0-9, ⑩=10)
LETTER = {"a": 11, "b": 12, "c": 13, "d": 14, "e": 15}


def to_idx(v):
    if isinstance(v, int):
        return v
    if isinstance(v, str) and v.lower() in LETTER:
        return LETTER[v.lower()]
    raise ValueError(v)


def write_exam(json_name: str, title: str, sections: dict, scores: dict) -> int:
    questions = []
    blanks = 0
    for field in ("1", "2", "3", "4"):
        subs = []
        for row in sections[field]:
            # allow (label, mark, correct, score) or accidental (label, mark, mark, correct, score)
            if len(row) == 5:
                label, mark, _dup, correct, score = row
            else:
                label, mark, correct, score = row
            if isinstance(correct, str) and ":" in correct:
                # already "ア: 1, イ: 2"
                answer = {"correct_option": correct, "correct_index": correct}
                blanks += correct.count(":")
            elif isinstance(correct, (list, tuple)):
                # list of ints aligned to marks
                marks = [m for m in mark.replace("・", " ").split() if m]
                pairs = []
                for m, c in zip(marks, correct):
                    pairs.append(f"{m}: {to_idx(c)}")
                s = ", ".join(pairs)
                answer = {"correct_option": s, "correct_index": s}
                blanks += len(pairs)
            else:
                idx = to_idx(correct)
                answer = {"correct_option": str(correct), "correct_index": idx}
                blanks += 1
            sc = score if isinstance(score, int) else 1
            subs.append(
                {
                    "question_id": f"{title} 第{field}問 {label} [{mark}]",
                    "label": label,
                    "mark_symbol": mark,
                    "score": sc,
                    "context": (
                        f"{title} 第{field}問 {label}（解答記号 {mark}）。"
                        "問題文・選択肢は問題PDFを参照し、マークで解答してください。"
                    ),
                    "options": [],
                    "answer": answer,
                    "explanation": f"正解は解答・解説PDFの第{field}問 {label}（{mark}）を参照。",
                }
            )
        questions.append(
            {
                "section_id": f"第{field}問",
                "section_title": f"第{field}問",
                "section_score": scores[field],
                "sub_questions": subs,
            }
        )
    data = {
        "metadata": {
            "title": title,
            "subject": "情報Ⅰ",
            "total_score": 100,
            "description": "解答記号ごとに分割したマーク採点用データ（公式／模試解答に準拠）",
        },
        "questions": questions,
    }
    text = json.dumps(data, ensure_ascii=False, indent=2)
    (DATA / json_name).write_text(text, encoding="utf-8")
    root = ROOT / json_name
    if root.exists():
        root.write_text(text, encoding="utf-8")
    print(f"  {json_name}: blanks={blanks}")
    return blanks


def fix_kawai2_answer_pages():
    """kawai-2025-2nd answerStart was 40 (instructions); true key starts at 41."""
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    src = next(s for s in cat["sources"] if s["id"] == "kawai-2025-2nd")
    pdf = ROOT / src["questionPdf"]
    doc = pymupdf.open(pdf)
    start = 41
    out_dir = OUT_A / "kawai-2025-2nd"
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    mat = pymupdf.Matrix(1.2, 1.2)
    urls = []
    for i in range(start - 1, len(doc)):
        pix = doc[i].get_pixmap(matrix=mat, alpha=False)
        name = f"p{i - (start - 1) + 1:02d}.png"
        pix.save(out_dir / name)
        urls.append(f"/exam-answers/kawai-2025-2nd/{name}")
    doc.close()
    src["answerStartPage"] = start
    src["answerPages"] = urls
    # trim Q4
    r4 = src["ranges"]["4"]
    r4["end"] = start - 1
    all_pages = [f"/exam-pages/kawai-2025-2nd/p{i:02d}.png" for i in range(1, src["pageCount"] + 1)]
    for n, r in src["ranges"].items():
        src["pages"][n] = all_pages[r["start"] - 1 : r["end"]]
    CATALOG.write_text(json.dumps(cat, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"fixed kawai-2025-2nd answerStart={start} pages={len(urls)}")


